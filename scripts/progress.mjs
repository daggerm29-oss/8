#!/usr/bin/env node
// Computes milestone percentages from docs/roadmap.md checkboxes and writes the
// dashboard into progress.md between the progress markers. Run: node scripts/progress.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const roadmapPath = join(root, 'docs/roadmap.md')
const progressPath = join(root, 'progress.md')
const START = '<!-- progress:start -->'
const END = '<!-- progress:end -->'

const milestones = []
let item = null
for (const line of readFileSync(roadmapPath, 'utf8').split('\n')) {
  const heading = line.match(/^## (M\d+)\s*[—-]\s*(.+)$/)
  if (heading) {
    milestones.push({ id: heading[1], name: heading[2].trim(), items: [] })
    item = null
    continue
  }
  const box = line.match(/^- \[( |x|X)\] (.+)$/)
  const milestone = milestones.at(-1)
  if (box && milestone) {
    item = { ticked: box[1] !== ' ', title: box[2].replace(/\*\*/g, '').split(' — ')[0].trim(), evidence: false }
    milestone.items.push(item)
  } else if (item && /^\s+- Evidence:\s*\S/.test(line)) {
    item.evidence = true
  } else if (/^\S/.test(line)) {
    item = null
  }
}

const unproven = []
for (const m of milestones) {
  for (const i of m.items) {
    if (i.ticked && !i.evidence) unproven.push(`${m.id}: ${i.title}`)
  }
  const counted = m.items.filter((i) => i.ticked && i.evidence)
  m.done = counted.length
  m.total = m.items.length
  m.next = m.items.find((i) => !(i.ticked && i.evidence))?.title ?? null
}

const pct = (done, total) => (total === 0 ? 0 : Math.round((done / total) * 100))
const bar = (p) => '█'.repeat(Math.round(p / 10)) + '░'.repeat(10 - Math.round(p / 10))
const done = milestones.reduce((s, m) => s + m.done, 0)
const total = milestones.reduce((s, m) => s + m.total, 0)
const current = milestones.find((m) => m.done < m.total)

const rows = milestones.map((m) => {
  const p = pct(m.done, m.total)
  const status =
    m.done === m.total ? 'Done' : m === current ? 'In progress' : m.done > 0 ? 'Partly built early' : 'Not started'
  return `| ${m.id} ${m.name} | ${bar(p)} ${p}% | ${m.done}/${m.total} | ${status} |`
})

const dashboard = [
  START,
  '<!-- Generated by `node scripts/progress.mjs` from docs/roadmap.md. Do not edit by hand. -->',
  '',
  '> These are **checklist completion** numbers (ticked items with recorded evidence ÷ all items). They are not a measure of product quality or release readiness; human launch gates in `docs/roadmap.md` are not counted.',
  '',
  `**Overall checklist completion: ${pct(done, total)}%** (${done}/${total} roadmap items)  `,
  `**Current milestone:** ${current ? `${current.id} ${current.name}` : 'All milestones complete'}  `,
  `**Next task:** ${current?.next ?? '—'}`,
  '',
  '| Milestone | Progress | Items | Status |',
  '| --- | --- | --- | --- |',
  ...rows,
  ...(unproven.length
    ? ['', `**Not counted — ticked without an \`Evidence:\` line (${unproven.length}):** ${unproven.join('; ')}`]
    : []),
  END,
].join('\n')

const progress = readFileSync(progressPath, 'utf8')
const startIdx = progress.indexOf(START)
const endIdx = progress.indexOf(END)
if (startIdx === -1 || endIdx === -1) {
  console.error(`progress.md is missing the ${START} / ${END} markers`)
  process.exit(1)
}
writeFileSync(progressPath, progress.slice(0, startIdx) + dashboard + progress.slice(endIdx + END.length))
console.log(dashboard.split('\n').slice(3, -1).join('\n'))
